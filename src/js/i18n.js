const languageButton = document.querySelector(".language-button");

const languageNames = {
  en: "English",
  fr: "Français",
  nl: "Nederlands",
};

let currentLanguage = localStorage.getItem("ssc-language") || "en";

if (!translations[currentLanguage]) {
  currentLanguage = "en";
}

function setText(selector, value) {
  const element = document.querySelector(selector);
  if (element) element.textContent = value;
}

function setHTML(selector, value) {
  const element = document.querySelector(selector);
  if (element) element.innerHTML = value;
}

function setAttribute(selector, attribute, value) {
  const element = document.querySelector(selector);
  if (element) element.setAttribute(attribute, value);
}

function applyLanguage(language) {
  const t = translations[language];
  if (!t) return;

  currentLanguage = language;
  document.documentElement.lang = language;
  localStorage.setItem("ssc-language", language);

  if (languageButton) {
    languageButton.textContent = language.toUpperCase();
    languageButton.setAttribute(
      "aria-label",
      `Selected language: ${languageNames[language]}`,
    );
    languageButton.setAttribute("title", languageNames[language]);
  }

  setText(".navigation__list li:nth-child(1) a", t.navServices);
  setText(".navigation__list li:nth-child(2) a", t.navAbout);
  setText(".navigation__list li:nth-child(3) a", t.navProjects);
  setText(".mobile-menu nav a:nth-child(1)", t.navServices);
  setText(".mobile-menu nav a:nth-child(2)", t.navAbout);
  setText(".mobile-menu nav a:nth-child(3)", t.navProjects);
  setText(".header-contact", t.contact);

  setText(".hero__eyebrow", t.heroEyebrow);
  setHTML(".hero__title", `${t.heroTitle}<span>${t.heroTitleAccent}</span>`);
  setText(".hero__subtitle", t.heroSubtitle);
  setText(".hero__description", t.heroDescription);
  setHTML(
    ".hero__button--primary",
    `${t.heroProjects}<span aria-hidden="true">→</span>`,
  );
  setHTML(
    ".hero__button--secondary",
    `${t.heroConsultation}<span aria-hidden="true">→</span>`,
  );
  setText(".hero__scroll span:nth-child(2)", t.scroll);

  setText(".services__eyebrow", t.servicesEyebrow);
  setText(".services__title", t.servicesTitle);
  setText(".services__description", t.servicesDescription);

  document.querySelectorAll(".service-card").forEach((card, index) => {
    const title = card.querySelector("h3");
    const description = card.querySelector("p");
    const button = card.querySelector(".service-card__more");

    if (title) title.textContent = t.serviceTitles[index];
    if (description) description.textContent = t.serviceDescriptions[index];
    if (button) {
      const arrow = button.querySelector("span");
      button.textContent = t.moreInfo + " ";
      if (arrow) {
        button.append(arrow);
      } else {
        const span = document.createElement("span");
        span.textContent = "↗";
        button.append(span);
      }
    }
  });

  setText(".section-heading__eyebrow", t.projectsEyebrow);
  setHTML(
    ".section-heading__title",
    `${t.projectsTitle} <span>${t.projectsTitleAccent}</span>`,
  );
  setText(".section-heading__text", t.projectsDescription);

  document.querySelectorAll(".project-card").forEach((card, index) => {
    const category = card.querySelector(".project-card__category");
    const title = card.querySelector(".project-card__title");

    if (category) category.textContent = t.projectCategories[index];
    if (title) title.textContent = t.projectTitles[index];
    card.dataset.caption = t.projectTitles[index];
  });

  setText(".about__eyebrow", t.aboutEyebrow);
  setHTML(
    ".about__title",
    `${t.aboutTitle}<br><span>${t.aboutTitleAccent}</span>`,
  );

  const aboutDescriptions = document.querySelectorAll(".about__description");
  if (aboutDescriptions[0]) aboutDescriptions[0].textContent = t.aboutLead;
  if (aboutDescriptions[1]) aboutDescriptions[1].textContent = t.aboutText1;
  if (aboutDescriptions[2]) aboutDescriptions[2].textContent = t.aboutText2;

  setHTML(
    ".about__button",
    `${t.aboutButton}<span aria-hidden="true">↗</span>`,
  );
  setText(".about__side-label", t.philosophy);
  setHTML(".about__side-text", t.philosophyText.split("|").join("<br>"));

  setText(".footer__heading", t.footerContact);
  setText(".footer__back-to-top", ` ${t.backToTop} ↑`);

  const footerParagraph = document.querySelector(".footer__bottom p");
  if (footerParagraph) {
    footerParagraph.innerHTML = `© <span id="footer-year">${new Date().getFullYear()}</span> Strong Stone Company. ${t.footerRights}`;
  }

  setText(".service-modal__subtitle", t.modalOffer);
  setText(".service-modal__contact", t.modalContact);
  setText(".service-modal__form-view .service-modal__title", t.formTitle);
  setText(
    ".service-modal__form-view .service-modal__description",
    t.formDescription,
  );

  const labels = {
    "#service-form-name": [t.nameLabel, t.namePlaceholder],
    "#service-form-email": [t.emailLabel, t.emailPlaceholder],
    "#service-form-phone": [t.phoneLabel, "+32 ..."],
    "#service-form-service": [t.serviceLabel, ""],
    "#service-form-message": [t.messageLabel, t.messagePlaceholder],
  };

  Object.entries(labels).forEach(([selector, [label, placeholder]]) => {
    const field = document.querySelector(selector);
    if (!field) return;

    const labelElement = document.querySelector(
      `label[for="${selector.slice(1)}"]`,
    );
    if (labelElement) labelElement.textContent = label;
    if (placeholder) field.setAttribute("placeholder", placeholder);
  });

  const serviceSelect = document.querySelector("#service-form-service");
  if (serviceSelect) {
    serviceSelect.options[0].textContent = t.selectService;
    t.serviceOptions.forEach((label, index) => {
      if (serviceSelect.options[index + 1]) {
        serviceSelect.options[index + 1].textContent = label;
      }
    });
  }

  const message = document.querySelector("#service-form-message");
  if (message) message.setAttribute("placeholder", t.messagePlaceholder);

  setText(".service-modal__back", t.back);
  setText(".service-modal__submit", t.send);

  document.dispatchEvent(
    new CustomEvent("ssc:languagechange", {
      detail: { language, translations: t },
    }),
  );
}

if (languageButton) {
  languageButton.addEventListener("click", () => {
    const languages = ["en", "fr", "nl"];
    const nextIndex =
      (languages.indexOf(currentLanguage) + 1) % languages.length;
    applyLanguage(languages[nextIndex]);
  });
}

applyLanguage(currentLanguage);

export { applyLanguage, translations };
